"""checkpoint_report.py's two kinds of report: a behaviour report (self-play) links the searched-leak
reports (the census written alone) of what it reports on, and the leaderboard links only the former."""

from __future__ import annotations

import pathlib

from tools.scripts import checkpoint_report as cr

NET = "E7-A1-R1-S44@100M"
PLAYER = f"{NET}~rollout(k=4,worlds=32,horizon=4,rule=z2)"


def _write(d: pathlib.Path, name: str, subject: str, selfplay: bool, leak: bool) -> pathlib.Path:
    kind = cr.BEHAVIOUR if selfplay else cr.LEAK
    lines = [f"# {subject}: {kind}", "", "Generated by `tools/scripts/checkpoint_report.py`.", "",
             "## The checkpoint", "", "* **File:** `x.pt`"]
    lines += [f"{cr.GAMES_LINE}16,384 greedy self-play games."] if selfplay else []
    lines += ["", cr.LEAK_HEADING, "", "the census"] if leak else []
    p = d / name
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


def test_a_networks_behaviour_report_links_its_players_leak_reports(tmp_path: pathlib.Path) -> None:
    net = _write(tmp_path, "net.md", NET, selfplay=True, leak=False)
    _write(tmp_path, "player_leak.md", PLAYER, selfplay=False, leak=True)
    other = _write(tmp_path, "other.md", "E7-A2-R1-S44@100M", selfplay=True, leak=False)
    # A network whose name starts the same is not this network.
    _write(tmp_path, "longer_leak.md", f"{NET}0~rollout(k=4)", selfplay=False, leak=True)
    cr.write_index(str(tmp_path))
    lines = net.read_text(encoding="utf-8").split("\n")
    at = next(i for i, line in enumerate(lines) if line.startswith(cr.GAMES_LINE))
    assert lines[at + 1].startswith(cr.LEAK_LINE) and "(player_leak.md)" in lines[at + 1]
    assert "longer_leak.md" not in lines[at + 1]
    assert cr.LEAK_LINE not in other.read_text(encoding="utf-8")
    # Rewriting is idempotent, and a census that goes away takes its link with it.
    once = net.read_text(encoding="utf-8")
    cr.write_index(str(tmp_path))
    assert net.read_text(encoding="utf-8") == once
    (tmp_path / "player_leak.md").unlink()
    cr.write_index(str(tmp_path))
    assert cr.LEAK_LINE not in net.read_text(encoding="utf-8")
    index = (tmp_path / "README.md").read_text(encoding="utf-8")
    assert "(net.md)" in index and "## Searched-leak reports" in index


def test_a_players_own_behaviour_report_links_its_census_written_alone(tmp_path: pathlib.Path) -> None:
    played = _write(tmp_path, "player.md", PLAYER, selfplay=True, leak=False)
    _write(tmp_path, "player_leak.md", PLAYER, selfplay=False, leak=True)
    # A behaviour report holding its census already links nothing to itself.
    inline = _write(tmp_path, "inline.md", f"{NET}~gumbel", selfplay=True, leak=True)
    cr.write_index(str(tmp_path))
    assert f"{cr.LEAK_LINE}[this player](player_leak.md)" in played.read_text(encoding="utf-8")
    assert cr.LEAK_LINE not in inline.read_text(encoding="utf-8")


def test_the_census_written_alone_is_titled_a_leak_report(tmp_path: pathlib.Path) -> None:
    ckpt = tmp_path / "E7-A1-R1-S44_20261001_000000" / "x.pt"
    ckpt.parent.mkdir()
    ckpt.write_bytes(b"weights")
    md = cr.report(str(ckpt), {"games": 0, "seed": 1, "batch": 1, "player": PLAYER}, False, 0, label=PLAYER,
                   note="n")
    assert md.split("\n")[0] == f"# {PLAYER}: {cr.LEAK}"
    assert cr.GAMES_LINE not in md
